#!/usr/bin/env python3
"""Generate the Python SDK from its pinned public OpenAPI without network access."""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
import keyword
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = "# Generated by scripts/generate.py. Do not edit.\n"
VERBS = {"get", "post", "put", "patch", "delete", "head", "options", "trace"}
SCHEMA_KEYS = {
    "$ref", "type", "format", "properties", "required", "items",
    "additionalProperties", "minimum", "maximum", "exclusiveMinimum",
    "exclusiveMaximum", "minLength", "maxLength", "minItems", "maxItems",
    "minProperties", "maxProperties", "propertyNames", "pattern", "enum",
    "const", "anyOf", "oneOf", "allOf", "uniqueItems", "nullable",
    "x-raims-enum-labels", "x-raims-max-utf8-bytes", "contentEncoding", "contentMediaType",
}
DOCUMENTATION_KEYS = {
    "title", "description", "example", "examples", "default", "deprecated",
    "readOnly", "writeOnly", "externalDocs", "xml", "$schema", "$id",
}


def read_json(relative):
    return json.loads((ROOT / relative).read_text(encoding="utf-8"))


def snake(value):
    value = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", value)
    value = re.sub(r"([A-Z])([A-Z][a-z])", r"\1_\2", value)
    return value.lower()


def pascal(value):
    value = unicodedata.normalize("NFKD", value).encode("ascii", "ignore").decode()
    return "".join(part[:1].upper() + part[1:] for part in re.findall(r"[A-Za-z0-9]+", value))


def identifier(value):
    if not isinstance(value, str) or not value.isidentifier() or keyword.iskeyword(value):
        raise ValueError("A public identifier cannot be represented in Python: " + repr(value))
    return value


def resolve(spec, value):
    seen = set()
    while "$ref" in value:
        reference = value["$ref"]
        if not reference.startswith("#/") or reference in seen:
            raise ValueError("Only non-circular local object references are supported.")
        seen.add(reference)
        target = spec
        for part in reference[2:].split("/"):
            target = target[part.replace("~1", "/").replace("~0", "~")]
        value = target
    return value


def compact(schema):
    if not isinstance(schema, dict):
        raise TypeError("Every schema must be an object.")
    if "allOf" in schema or "oneOf" in schema:
        raise ValueError("allOf and oneOf schemas are not supported by response hydration.")
    if "anyOf" in schema:
        variants = schema["anyOf"]
        if not isinstance(variants, list) or len(variants) != 2 or not all(isinstance(part, dict) for part in variants) or sum(part.get("type") == "null" for part in variants) != 1:
            raise ValueError("Only nullable anyOf schemas are supported.")
    kinds = schema.get("type")
    if isinstance(kinds, list) and (not kinds or len(kinds) != len(set(kinds)) or len([kind for kind in kinds if kind != "null"]) > 1):
        raise ValueError("Only a single schema type with optional null is supported.")
    unknown = set(schema) - SCHEMA_KEYS - DOCUMENTATION_KEYS
    if unknown:
        raise ValueError("Unsupported schema keywords: " + ", ".join(sorted(unknown)))
    result = {}
    for key, value in schema.items():
        if key not in SCHEMA_KEYS:
            continue
        if key == "properties":
            result[key] = {name: compact(child) for name, child in value.items()}
        elif key in {"items", "propertyNames"} or key == "additionalProperties" and isinstance(value, dict):
            result[key] = compact(value)
        elif key in {"anyOf", "oneOf", "allOf"}:
            result[key] = [compact(child) for child in value]
        else:
            result[key] = copy.deepcopy(value)
    return result


def flatten_object(schema, schemas):
    """Resolve object composition for annotations without weakening validation metadata."""
    if "$ref" in schema:
        return flatten_object(schemas[schema["$ref"].rsplit("/", 1)[-1]], schemas)
    if "allOf" in schema:
        merged = {"type": "object", "properties": {}, "required": []}
        for part in schema["allOf"]:
            item = flatten_object(part, schemas)
            if item.get("type") != "object":
                raise ValueError("Only object allOf compositions can be represented.")
            for key, value in item.get("properties", {}).items():
                if key in merged["properties"] and merged["properties"][key] != value:
                    raise ValueError("Conflicting allOf properties cannot be represented.")
                merged["properties"][key] = value
            merged["required"].extend(item.get("required", []))
        return merged
    return schema


def object_type(schema):
    types = schema.get("type")
    return types == "object" or isinstance(types, list) and "object" in types


def normalize_schema(schema, suggested, schemas, hoist=False):
    result = copy.deepcopy(schema)
    for key, value in schema.items():
        if key == "properties":
            result[key] = {name: normalize_schema(child, suggested + pascal(name), schemas, True) for name, child in value.items()}
        elif key in {"items", "additionalProperties"} and isinstance(value, dict):
            result[key] = normalize_schema(value, suggested + "Item", schemas, True)
        elif key in {"anyOf", "oneOf", "allOf"}:
            result[key] = [normalize_schema(part, suggested + "Variant" + str(i + 1), schemas, True) for i, part in enumerate(value)]
    if hoist and object_type(result) and result.get("properties"):
        nullable = result.get("nullable") or isinstance(result.get("type"), list) and "null" in result["type"]
        model = dict(result, type="object")
        model.pop("nullable", None)
        if suggested in schemas and schemas[suggested] != model:
            raise ValueError("Inline schema name collision: " + suggested)
        identifier(suggested)
        schemas[suggested] = model
        reference = {"$ref": "#/components/schemas/" + suggested}
        return {"anyOf": [reference, {"type": "null"}]} if nullable else reference
    return result


def normalized_schemas(spec):
    schemas = {name: compact(schema) for name, schema in spec["components"]["schemas"].items()}
    for name in schemas:
        identifier(name)
    for name in list(schemas):
        schemas[name] = normalize_schema(schemas[name], name, schemas)
    return schemas


def refs(schema):
    result = set()
    if isinstance(schema, dict):
        if "$ref" in schema:
            reference = schema["$ref"]
            if not reference.startswith("#/components/schemas/"):
                raise ValueError("Schema references must target components.schemas.")
            result.add(reference.rsplit("/", 1)[-1])
        for value in schema.values():
            result.update(refs(value))
    elif isinstance(schema, list):
        for value in schema:
            result.update(refs(value))
    return result


def reachable(roots, schemas):
    result = set()
    for root in roots:
        result.update(refs(root))
    pending = list(result)
    while pending:
        name = pending.pop()
        if name not in schemas:
            raise ValueError("Unresolved schema: " + name)
        for child in refs(schemas[name]):
            if child not in result:
                result.add(child)
                pending.append(child)
    return result


def type_for(schema, schemas, input_type=False, qualify=False):
    if schema.get("nullable"):
        non_nullable = dict(schema)
        non_nullable.pop("nullable")
        return type_for(non_nullable, schemas, input_type, qualify) + " | None"
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        prefix = "types." if input_type else "models."
        return prefix + name if qualify else name
    if "allOf" in schema:
        return type_for(flatten_object(schema, schemas), schemas, input_type, qualify)
    if schema.get("anyOf") or schema.get("oneOf"):
        parts = schema.get("anyOf") or schema["oneOf"]
        return " | ".join(dict.fromkeys(type_for(part, schemas, input_type, qualify) for part in parts))
    if isinstance(schema.get("type"), list):
        return " | ".join(dict.fromkeys(type_for(dict(schema, type=part), schemas, input_type, qualify) for part in schema["type"]))
    kind = schema.get("type")
    if kind == "null":
        return "None"
    if input_type and schema.get("enum") and all(isinstance(value, (str, int, bool)) or value is None for value in schema["enum"]):
        return "Literal[" + ", ".join(repr(value) for value in schema["enum"]) + "]"
    if kind == "array":
        return "Sequence[" + type_for(schema.get("items", {}), schemas, input_type, qualify) + "]"
    if object_type(schema) or "properties" in schema:
        if schema.get("properties"):
            raise ValueError("Inline objects must be normalized to named schemas.")
        additional = schema.get("additionalProperties")
        value = type_for(additional, schemas, input_type, qualify) if isinstance(additional, dict) else "Any"
        return ("dict" if input_type else "Mapping") + "[str, " + value + "]"
    result = {"integer": "int", "number": "int | float" if input_type else "Decimal | int", "string": "str", "boolean": "bool"}.get(kind)
    if result is None:
        if not schema:
            return "Any"
        raise ValueError("A schema has no representable Python type: " + repr(schema))
    return result


def collect_operations(spec, source, schemas):
    operations = {}
    input_roots = []
    response_roots = []
    for path, item in spec["paths"].items():
        if not path.startswith("/v1/"):
            raise ValueError("Only versioned public product endpoints can be generated.")
        for verb, operation in item.items():
            if verb not in VERBS:
                continue
            name = identifier(operation.get("operationId"))
            if name in operations:
                raise ValueError("Operation IDs must be unique.")
            if operation.get("x-raims-availability", "production") != "production":
                raise ValueError("An operation has not been published.")
            if not any("BearerAuth" in entry for entry in operation.get("security", spec.get("security", []))):
                raise ValueError("An operation does not support API key authentication.")
            parameters = [resolve(spec, p) for p in item.get("parameters", []) + operation.get("parameters", [])]
            query_parameters = [p for p in parameters if p["in"] == "query"]
            for parameter in parameters:
                oauth_only = parameter.get("x-raims-authentication") == "oauth" or parameter.get("x-raims-security-schemes") == ["ApplicationOAuth"]
                if parameter["in"] == "header" and parameter["name"] != "Idempotency-Key" and not oauth_only:
                    raise ValueError("Unsupported public header parameter: " + parameter["name"])
            path_params = re.findall(r"\{([^}]+)\}", path)
            for param in path_params:
                identifier(param)
                if not any(p["in"] == "path" and p["name"] == param and p.get("required") for p in parameters):
                    raise ValueError("Every path placeholder requires a declared path parameter.")
            request_body = resolve(spec, operation["requestBody"]) if operation.get("requestBody") else None
            body_schema = request_body.get("content", {}).get("application/json", {}).get("schema") if request_body else None
            if request_body and not body_schema:
                raise ValueError("Only JSON request bodies can be generated.")
            query_schema = {
                "type": "object", "properties": {p["name"]: compact(p["schema"]) for p in query_parameters},
                "required": [p["name"] for p in query_parameters if p.get("required")],
            }
            params_schema = normalize_schema(compact(body_schema), name + "RequestBody", schemas, True) if body_schema else normalize_schema(query_schema, name + "Params", schemas)
            responses = {}
            for status, response in operation["responses"].items():
                response = resolve(spec, response)
                content = response.get("content")
                schema = content.get("application/json", {}).get("schema") if content else None
                normalized_response = normalize_schema(compact(schema), name + "Response" + status, schemas, True) if schema else None
                if normalized_response:
                    response_roots.append(normalized_response)
                if not re.fullmatch(r"2\d\d", status):
                    continue
                if content and not schema:
                    raise ValueError("Only JSON success responses can be generated.")
                responses[status] = normalized_response
            if not responses:
                raise ValueError("An operation has no declared success response.")
            success_objects = [flatten_object(schema, schemas) for schema in responses.values() if schema]
            paginated = any("list" in value.get("properties", {}) and "page" in value.get("properties", {}) for value in success_objects)
            if paginated and (verb != "get" or any("list" not in value.get("properties", {}) or "page" not in value.get("properties", {}) for value in success_objects) or not {"after", "before"}.issubset(query_schema["properties"])):
                raise ValueError("The cursor pagination contract cannot be represented.")
            input_roots.append(params_schema)
            operations[name] = {
                "id": name, "method": verb.upper(), "path": path, "pathParams": path_params,
                "query": query_schema["properties"], "body": bool(body_schema),
                "body_required": bool(request_body and request_body.get("required")),
                "params_schema": params_schema,
                "idempotency": any(p["in"] == "header" and p["name"] == "Idempotency-Key" for p in parameters),
                "maxBodyBytes": operation.get("x-raims-max-body-bytes"),
                "responses": responses, "paginated": paginated,
                "summary": " ".join(operation.get("summary", name).split()),
            }
    if len(operations) != source["operations"] or spec["info"]["version"] != source["api_version"]:
        raise ValueError("The operation count or API version differs from source.json.")
    return operations, reachable(input_roots, schemas), reachable(response_roots, schemas)


def typed_dict(name, schema, schemas):
    schema = flatten_object(schema, schemas)
    if not object_type(schema):
        raise ValueError("TypedDict inputs must be object schemas.")
    properties = schema.get("properties", {})
    required = set(schema.get("required", []))
    if not required.issubset(properties):
        raise ValueError("A required property is not declared.")
    lines = []
    base = "TypedDict"
    if required:
        base = "_" + name + "Required"
        lines.append("class " + base + "(TypedDict):")
        for field, child in properties.items():
            if field in required:
                lines.append("    " + identifier(field) + ": " + type_for(child, schemas, True))
        lines.append("")
    lines.append("class " + name + "(" + base + ", total=False):")
    optional = [field for field in properties if field not in required]
    for field in optional:
        lines.append("    " + identifier(field) + ": " + type_for(properties[field], schemas, True))
    if not optional:
        lines.append("    pass")
    lines.append("")
    return "\n".join(lines)


def python_module(definitions, relative_imports=(), extra_imports=()):
    body = "\n\n".join(part.rstrip() for part in definitions) + "\n"
    imports = []
    for module, candidates in (
        ("collections.abc", ("Mapping", "Sequence")),
        ("decimal", ("Decimal",)),
        ("typing", ("Any", "Literal", "TypeAlias", "TypedDict", "cast")),
    ):
        needed = [name for name in candidates if re.search(r"\b" + name + r"\b", body)]
        if needed:
            imports.append("from " + module + " import " + ", ".join(needed))
    imports.extend(extra_imports)
    if relative_imports:
        imports.append("")
        imports.extend(relative_imports)
    return HEADER + "\nfrom __future__ import annotations\n\n" + "\n".join(imports) + "\n\n\n" + body


def generate_types(operations, schemas, names):
    parts = []
    for name in sorted(names):
        schema = flatten_object(schemas[name], schemas)
        if object_type(schema):
            parts.append(typed_dict(name, schema, schemas))
        else:
            parts.append(name + " = " + type_for(schema, schemas, True) + "\n")
    for name, operation in operations.items():
        if operation["body"] or operation["query"]:
            parts.append(typed_dict(name + "Params", operation["params_schema"], schemas))
    return python_module(parts)


def generate_models(schemas, names, operations):
    parts = []
    for name in sorted(names):
        schema = flatten_object(schemas[name], schemas)
        if not object_type(schema):
            raise ValueError("Named response models must be objects.")
        lines = ["class " + name + "(ApiResource):"]
        for field, child in schema.get("properties", {}).items():
            field = identifier(field)
            annotation = type_for(child, schemas)
            lines.extend(["    @property", "    def " + field + "(self) -> " + annotation + ":", "        return cast(" + annotation + ", self._get_field(" + repr(field) + "))", ""])
        if not schema.get("properties"):
            lines.append("    pass")
        parts.append("\n".join(lines) + "\n")
    page_types = set()
    for operation in operations.values():
        if not operation["paginated"]:
            continue
        for response in operation["responses"].values():
            if response:
                page = flatten_object(response, schemas)["properties"]["page"]
                page_types.add(type_for(page, schemas))
    if not page_types:
        raise ValueError("The pagination metadata type requires a published paginated operation.")
    if "PageInfo" in names:
        raise ValueError("The pagination metadata alias collides with a response model.")
    parts.append("PageInfo: TypeAlias = " + " | ".join(sorted(page_types)) + "\n")
    return python_module(parts, ["from ._resource import ApiResource"])


def response_type(operation, schemas, asynchronous=False):
    if operation["paginated"]:
        schema = next(schema for schema in operation["responses"].values() if schema)
        obj = flatten_object(schema, schemas)
        items = obj["properties"]["list"]["items"]
        collection = "AsyncApiList" if asynchronous else "ApiList"
        return collection + "[" + type_for(items, schemas, qualify=True) + "]"
    return " | ".join(dict.fromkeys(type_for(schema, schemas, qualify=True) if schema else "None" for schema in operation["responses"].values()))


def generate_services(services, operations, schemas):
    parts = []
    for service, methods in services.items():
        for asynchronous in (False, True):
            prefix = "Async" if asynchronous else ""
            parts.append("class " + prefix + pascal(service) + "Service:\n    def __init__(self, client: Any) -> None:\n        self._client = client\n")
            for method, name in methods.items():
                operation = operations[name]
                has_params = operation["body"] or bool(operation["query"])
                required = operation["body_required"] if operation["body"] else bool(flatten_object(operation["params_schema"], schemas).get("required"))
                args = ["self"] + [field + ": str" for field in operation["pathParams"]]
                if has_params:
                    args.append("params: types." + name + "Params" + ("" if required else " | None = None"))
                args.extend(["*", "options: RequestOptions | None = None"])
                signature = ("async " if asynchronous else "") + "def " + method + "(" + ", ".join(args) + ") -> " + response_type(operation, schemas, asynchronous) + ":"
                path = "{" + ", ".join(repr(field) + ": " + field for field in operation["pathParams"]) + "}"
                call = "self._client._request(" + repr(name) + ", path_params=" + path + ", params=" + ("params" if has_params else "None") + ", options=options)"
                parts.append("    " + signature + "\n        " + repr(operation["summary"]) + "\n        return " + ("await " if asynchronous else "") + call + "\n")
    return python_module(parts, ["from . import models, types", "from ._options import RequestOptions", "from ._pagination import ApiList, AsyncApiList"])


def enum_constants(schemas):
    constants = {}

    def add(name, value):
        if name in constants and constants[name] != value:
            raise ValueError("An enum constant name collides: " + name)
        constants[name] = value

    def walk(schema, path):
        if schema.get("enum"):
            values = schema["enum"]
            labels = schema.get("x-raims-enum-labels")
            if labels is not None and (len(labels) != len(values) or not all(isinstance(label, str) for label in labels)):
                raise ValueError("Explicit enum labels must match their values.")
            for index, value in enumerate(values):
                label = labels[index] if labels else value if isinstance(value, str) else None
                if label is None:
                    continue
                name = re.sub(r"[^A-Z0-9]+", "_", snake(path + "_" + str(label)).upper()).strip("_")
                identifier(name)
                add(name, value)
        for field, child in schema.get("properties", {}).items():
            walk(child, path + "_" + field)
        for key in ("items", "additionalProperties"):
            if isinstance(schema.get(key), dict):
                walk(schema[key], path + "_item")
        for key in ("anyOf", "oneOf", "allOf"):
            for child in schema.get(key, []):
                walk(child, path)

    for name, schema in schemas.items():
        walk(schema, name)
    return constants


def reference_translations():
    catalog = read_json("docs/reference.en.json")
    translations = catalog.get("translations")
    if catalog.get("locale") != "en" or not isinstance(translations, dict):
        raise ValueError("The reference requires an English editorial translation catalog.")
    if any(not isinstance(source, str) or not source or not isinstance(target, str) or not target.strip()
           for source, target in translations.items()):
        raise ValueError("Reference translations must map exact nonempty source text to English text.")
    return translations


def reference_text(source, translations):
    if not source:
        return ""
    if source not in translations:
        raise ValueError("Missing English reference translation for exact source: " + repr(source))
    return " ".join(translations[source].split())


def generate_reference(source, services, operations, schemas, constants, spec):
    translations = reference_translations()
    lines = ["# Python SDK reference", "", "Generated from the public contract pinned in `contracts/source.json`.", "", "The same services are available in `RaimsClient` and `AsyncRaimsClient`. Asynchronous client methods use `await`.", "", "| Service and method | HTTP operation | Input | Synchronous response |", "| --- | --- | --- | --- |"]
    for service, methods in services.items():
        path = "simulations.charges" if service == "simulation_charges" else "simulations.refunds" if service == "simulation_refunds" else service
        for method, name in methods.items():
            operation = operations[name]
            params = "[`" + name + "Params`](#" + name.lower() + "params)" if operation["body"] or operation["query"] else "-"
            result = response_type(operation, schemas).replace("models.", "").replace(" | ", " or ")
            lines.append("| `" + path + "." + method + "` | `" + operation["method"] + " " + operation["path"] + "` | " + params + " | `" + result + "` |")
    lines.extend(["", "Paginated lists return `ApiList[T]` in the synchronous client and `AsyncApiList[T]` in the asynchronous client. Iterating over a page does not send another request. Use `auto_paging_iter()` to visit subsequent pages. The `page` metadata uses the generated `PageInfo` type.", "", "Inputs use the API's JSON names. Omitting a field and sending `None` are distinct actions. Responses preserve new fields and values; monetary amounts remain integer cents, and resource dates use Unix seconds UTC.", "", "## Input parameters", "", "The fields and descriptions below come from the pinned public contract. `None` corresponds to `null`; an optional field may be omitted. Nested objects and lists have their own types in `raims.types`."])
    for name, operation in operations.items():
        if not operation["body"] and not operation["query"]:
            continue
        normalized = flatten_object(operation["params_schema"], schemas)
        raw_operation = spec["paths"][operation["path"]][operation["method"].lower()]
        if operation["body"]:
            raw_body = resolve(spec, raw_operation["requestBody"])
            documented = resolve(spec, raw_body["content"]["application/json"]["schema"]).get("properties", {})
        else:
            item = spec["paths"][operation["path"]]
            documented = {parameter["name"]: parameter for parameter in (resolve(spec, value) for value in item.get("parameters", []) + raw_operation.get("parameters", [])) if parameter["in"] == "query"}
        required = operation["body_required"] if operation["body"] else bool(normalized.get("required"))
        summary = reference_text(raw_operation.get("summary", name), translations)
        lines.extend(["", "### " + name + "Params", "", summary + ". The `params` argument is " + ("required." if required else "optional."), "", "| Field | Type | Required | Description |", "| --- | --- | --- | --- |"])
        for field, child in normalized.get("properties", {}).items():
            description = reference_text(documented.get(field, {}).get("description", ""), translations).replace("|", "\\|")
            annotation = type_for(child, schemas, True).replace("|", "\\|")
            lines.append("| `" + field + "` | `" + annotation + "` | " + ("Yes" if field in normalized.get("required", []) else "No") + " | " + (description or "-") + " |")
    lines.extend(["", "## Named public values", "", "Constants in `raims.enum_values` come from the public contract's enums. Numeric values receive names only when the contract publishes explicit labels. Constants use `Final` to preserve their literal types.", "", "| Constant | Value |", "| --- | --- |"])
    for name, value in sorted(constants.items()):
        lines.append("| `" + name + "` | `" + str(value).replace("|", "\\|") + "` |")
    return "\n".join(lines) + "\n"


def expected_outputs():
    source = read_json("contracts/source.json")
    raw = (ROOT / "contracts/openapi.json").read_bytes()
    if hashlib.sha256(raw).hexdigest() != source["sha256"]:
        raise ValueError("The pinned OpenAPI checksum differs from source.json.")
    if not re.fullmatch(r"[0-9a-f]{40}", source["revision"]):
        raise ValueError("The public source must have an immutable Git revision.")
    expected_url = "https://raw.githubusercontent.com/raimshq/openapi/" + source["revision"] + "/latest/openapi.spec3.json"
    if source["repository"] != "https://github.com/raimshq/openapi" or source["url"] != expected_url:
        raise ValueError("The source URL must identify the pinned public contract.")
    spec = json.loads(raw)
    schemas = normalized_schemas(spec)
    operations, inputs, responses = collect_operations(spec, source, schemas)
    services = read_json("contracts/service-map.json")
    mapped = []
    for service, methods in services.items():
        identifier(service)
        if snake(service) != service:
            raise ValueError("Service names must use snake_case.")
        for method, operation in methods.items():
            identifier(method)
            if snake(method) != method or operation not in operations:
                raise ValueError("Service methods must map snake_case names to published operations.")
            mapped.append(operation)
    if len(mapped) != len(set(mapped)) or set(mapped) != set(operations):
        raise ValueError("The service map must cover each published operation exactly once.")
    constants = enum_constants(schemas)
    metadata = {"source": source, "services": services, "operations": operations, "schemas": schemas}
    enum_lines = [HEADER, "from __future__ import annotations\n", "from typing import Final\n"] + [name + ": Final = " + repr(value) for name, value in sorted(constants.items())]
    return {
        "src/raims/_generated/contract.json": json.dumps(metadata, ensure_ascii=False, indent=2) + "\n",
        "src/raims/types.py": generate_types(operations, schemas, inputs),
        "src/raims/models.py": generate_models(schemas, responses, operations),
        "src/raims/services.py": generate_services(services, operations, schemas),
        "src/raims/enum_values.py": "\n".join(enum_lines) + "\n",
        "docs/reference.md": generate_reference(source, services, operations, schemas, constants, spec),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated files without modifying them.")
    args = parser.parse_args()
    outputs = expected_outputs()
    changed = []
    for relative, text in outputs.items():
        destination = ROOT / relative
        content = text.encode("utf-8")
        if destination.exists() and destination.read_bytes() == content:
            continue
        changed.append(relative)
        if not args.check:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(content)
    if args.check and changed:
        print("Generated files differ: " + ", ".join(changed), file=sys.stderr)
        return 1
    print(("Checked" if args.check else "Generated") + " " + str(read_json("contracts/source.json")["operations"]) + " published operations and " + str(len(outputs)) + " deterministic outputs.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (KeyError, TypeError, ValueError) as error:
        print("Generation failed: " + str(error), file=sys.stderr)
        raise SystemExit(1)
